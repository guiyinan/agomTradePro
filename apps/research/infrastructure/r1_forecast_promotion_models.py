_ModelT = TypeVar("_ModelT", bound=models.Model)
R1_OWNER_RECEIPT_CLOCK_SKEW = timedelta(seconds=5)


def _require_recent_owner_clock(value: datetime | None, field_name: str) -> None:
    now = timezone.now()
    if value is None or value > now or now - value > R1_OWNER_RECEIPT_CLOCK_SKEW:
        raise ValidationError(f"{field_name} must be generated by the Research owner repository.")


class R1PromotionAppendOnlyQuerySet(AppendOnlyQuerySet[_ModelT]):
    """Reject every bulk insertion shortcut for exact evidence rows."""

    def bulk_create(
        self,
        objs: Iterable[_ModelT],
        batch_size: int | None = None,
        ignore_conflicts: bool = False,
        update_conflicts: bool = False,
        update_fields: Collection[str] | None = None,
        unique_fields: Collection[str] | None = None,
    ) -> NoReturn:
        """Reject normal, ignore-conflict and update-conflict bulk inserts."""

        raise ValidationError("R1 promotion evidence requires exact append operations.")


class R1PromotionAppendOnlyManager(AppendOnlyManager[_ModelT]):
    """Expose the same guard through default, base and related managers."""

    def get_queryset(self) -> R1PromotionAppendOnlyQuerySet[_ModelT]:
        """Return the R1 promotion-specific guarded QuerySet."""

        return R1PromotionAppendOnlyQuerySet(self.model, using=self._db)

    def bulk_create(
        self,
        objs: Iterable[_ModelT],
        batch_size: int | None = None,
        ignore_conflicts: bool = False,
        update_conflicts: bool = False,
        update_fields: Collection[str] | None = None,
        unique_fields: Collection[str] | None = None,
    ) -> NoReturn:
        """Reject manager-level bulk inserts and both conflict modes."""

        raise ValidationError("R1 promotion evidence requires exact append operations.")


class R1PromotionAppendOnlyModel(models.Model):
    """Permit only database-assigned primary-key inserts."""

    objects = R1PromotionAppendOnlyManager()

    class Meta:
        abstract = True
        base_manager_name = "objects"
        default_manager_name = "objects"

    def save(
        self,
        *,
        force_insert: bool | tuple[ModelBase, ...] = False,
        force_update: bool = False,
        using: str | None = None,
        update_fields: Iterable[str] | None = None,
    ) -> None:
        """Reject updates and explicit primary keys, including zero."""

        if force_update or update_fields is not None or self.pk is not None:
            raise ValidationError("R1 promotion evidence is append-only.")
        super().save(force_insert=force_insert, using=using)

    def delete(
        self,
        using: object | None = None,
        keep_parents: bool = False,
    ) -> tuple[int, dict[str, int]]:
        """Reject instance deletion."""

        raise ValidationError("R1 promotion evidence cannot be deleted.")


