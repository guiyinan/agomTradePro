from __future__ import annotations

import argparse
import base64
import copy
import json
import mimetypes
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Any, cast

BASE_DIR = Path(__file__).resolve().parent
REPO_ROOT = BASE_DIR.parents[1]
CONTENT_TOKEN = "__ROADSHOW_CONTENT_JSON__"
SUPPORTED_IMAGE_TYPES = {"image/png", "image/jpeg", "image/gif", "image/webp", "image/svg+xml"}


@dataclass(frozen=True)
class BuildStats:
    slides: int
    images: int
    size_bytes: int


def _read_content(content_path: Path) -> dict[str, Any]:
    data = json.loads(content_path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise ValueError("Roadshow content root must be a JSON object")
    slides = data.get("slides")
    if not isinstance(slides, list) or not slides:
        raise ValueError("Roadshow content must contain a non-empty slides array")
    if not all(isinstance(slide, dict) for slide in slides):
        raise ValueError("Every slide must be a JSON object")
    return cast(dict[str, Any], data)


def _inline_image(image: dict[str, Any], content_dir: Path) -> None:
    source = image.get("src")
    if not isinstance(source, str) or not source:
        raise ValueError("Every image must contain a non-empty src")
    if source.startswith("data:"):
        return
    if "://" in source:
        raise ValueError(f"External images are not allowed in the offline release: {source}")

    image_path = (content_dir / source).resolve()
    if not image_path.is_relative_to(REPO_ROOT):
        raise ValueError(f"Image must stay inside the repository: {source}")
    if not image_path.is_file():
        raise FileNotFoundError(f"Roadshow image not found: {image_path}")

    mime_type, _ = mimetypes.guess_type(image_path.name)
    if mime_type not in SUPPORTED_IMAGE_TYPES:
        raise ValueError(f"Unsupported image type for {image_path}: {mime_type}")
    encoded = base64.b64encode(image_path.read_bytes()).decode("ascii")
    image["src"] = f"data:{mime_type};base64,{encoded}"


def _inline_images(node: Any, content_dir: Path) -> int:
    if isinstance(node, dict):
        count = 0
        for key, value in node.items():
            if key == "image" and isinstance(value, dict):
                image = cast(dict[str, Any], value)
                _inline_image(image, content_dir)
                count += 1
            else:
                count += _inline_images(value, content_dir)
        return count
    if isinstance(node, list):
        return sum(_inline_images(item, content_dir) for item in node)
    return 0


def _serialize_for_html(content: dict[str, Any]) -> str:
    serialized = json.dumps(content, ensure_ascii=False, separators=(",", ":"))
    return (
        serialized.replace("&", "\\u0026")
        .replace("<", "\\u003c")
        .replace(">", "\\u003e")
        .replace("\u2028", "\\u2028")
        .replace("\u2029", "\\u2029")
    )


def build_release(content_path: Path, template_path: Path, output_path: Path) -> BuildStats:
    """Build a deterministic, offline HTML release with inline content and images."""
    content = copy.deepcopy(_read_content(content_path))
    image_count = _inline_images(content, content_path.resolve().parent)
    template = template_path.read_text(encoding="utf-8")
    if template.count(CONTENT_TOKEN) != 1:
        raise ValueError(f"Template must contain exactly one {CONTENT_TOKEN} token")

    html = template.replace(CONTENT_TOKEN, _serialize_for_html(content))
    html = (
        "<!-- Generated by docs/roadshow/build_release.py; edit roadshow.json or template.html instead. -->\n"
        + html
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)
    temporary_path = output_path.with_name(output_path.name + ".tmp")
    try:
        temporary_path.write_text(html, encoding="utf-8", newline="\n")
        temporary_path.replace(output_path)
    finally:
        if temporary_path.exists():
            temporary_path.unlink()

    slides = content["slides"]
    return BuildStats(
        slides=len(cast(list[Any], slides)),
        images=image_count,
        size_bytes=output_path.stat().st_size,
    )


def _default_output_path() -> Path:
    timestamp = datetime.now().astimezone().strftime("%Y%m%d-%H%M%S")
    return BASE_DIR / f"agomtradepro-roadshow-inline-{timestamp}.html"


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Build the self-contained AgomTradePro roadshow HTML"
    )
    parser.add_argument("--content", type=Path, default=BASE_DIR / "roadshow.json")
    parser.add_argument("--template", type=Path, default=BASE_DIR / "template.html")
    parser.add_argument("--output", type=Path, default=_default_output_path())
    return parser.parse_args()


def main() -> int:
    """Generate the release file from command-line arguments and print a summary."""
    args = _parse_args()
    stats = build_release(args.content, args.template, args.output)
    size_mib = stats.size_bytes / (1024 * 1024)
    print(
        f"Generated {args.output} | {stats.slides} slides | "
        f"{stats.images} inline images | {size_mib:.2f} MiB"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
